/**
 * Returns state data matching GeoJSON state name
 */
export function getStateByGeoJsonName(geoName: string): IndiaState | undefined {
  if (!geoName) return undefined;
  const n = geoName.toLowerCase().trim();
  return INDIA_STATES_DATA.find((s) => {
    const sName = s.name.toLowerCase();
    if (sName === n) return true;
    if (n === 'orissa' && (sName.includes('odisha') || s.id === 'odisha')) return true;
    if (n === 'uttaranchal' && (sName.includes('uttarakhand') || s.id === 'uttarakhand')) return true;
    if (n === 'delhi' && (sName.includes('delhi') || s.id === 'delhi')) return true;
    if (n.includes('jammu') && sName.includes('jammu')) return true;
    if (n.includes('andaman') && sName.includes('andaman')) return true;
    if (n.includes('dadra') || n.includes('daman')) return s.id === 'dadra-daman';
    return sName.includes(n) || n.includes(sName);
  });
}

/**
 * Returns a flat array of all cities across all Indian states and Union Territories
 */
export function getAllCitiesFlat(): IndiaCity[] {
  return INDIA_STATES_DATA.flatMap((state) => state.cities);
}

/**
 * Returns the top N most polluted Indian cities sorted by AQI descending (aqicn & aqi.in style)
 */
export function getMostPollutedCities(limit: number = 10): IndiaCity[] {
  return [...getAllCitiesFlat()]
    .sort((a, b) => b.aqi - a.aqi)
    .slice(0, limit);
}

/**
 * Returns the top N cleanest Indian cities sorted by AQI ascending (aqicn & aqi.in style)
 */
export function getCleanestCities(limit: number = 10): IndiaCity[] {
  return [...getAllCitiesFlat()]
    .sort((a, b) => a.aqi - b.aqi)
    .slice(0, limit);
}

/**
 * Calculates cigarette equivalence per 24 hours based on Berkeley Earth's scientific formula:
 * 1 cigarette ≈ 22 µg/m³ of PM2.5 inhalation per 24 hours
 */
export function calculateCigaretteEquivalence(pm25: number): {
  cigarettes: number;
  label: string;
  severity: 'low' | 'moderate' | 'high' | 'extreme';
} {
  const safePm25 = Math.max(0, pm25);
  const count = Math.round((safePm25 / 22) * 10) / 10;
  
  if (count < 1) {
    return {
      cigarettes: count,
      label: 'Minimal equivalent smoke exposure',
      severity: 'low',
    };
  } else if (count < 5) {
    return {
      cigarettes: count,
      label: `Equivalent to smoking ${count} cigarettes/day`,
      severity: 'moderate',
    };
  } else if (count < 15) {
    return {
      cigarettes: count,
      label: `Equivalent to smoking ${count} cigarettes/day`,
      severity: 'high',
    };
  } else {
    return {
      cigarettes: count,
      label: `Emergency: Equivalent to smoking ${count} cigarettes/day!`,
      severity: 'extreme',
    };
  }
}
